"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const source=fs.readFileSync("static/chart-studio-averages.js","utf8");
const ctx={window:{},localStorage:{getItem(){return null},setItem(){}},document:{},console};
vm.runInNewContext(source,ctx,{filename:"chart-studio-averages.js"});
const ma=ctx.window.ChartStudioAverages;
function almost(actual,expected){assert.ok(Math.abs(actual-expected)<1e-9,actual+" != "+expected)}
const base=1700000000;
const candles=[10,20,30,40,50].map((value,i)=>({
 time:base+i*900,open:value+1,high:value+4,low:value-4,close:value
}));
assert.deepEqual(Array.from(ma.calculate(candles,"SMA",3),x=>x.value),[20,30,40]);
const exponential=ma.calculate(candles,"EMA",3);
assert.equal(exponential.length,3);
almost(exponential[0].value,22.5);
almost(exponential[1].value,31.25);
almost(exponential[2].value,40.625);
const weighted=ma.calculate(candles,"WMA",3);
almost(weighted[0].value,(10+20*2+30*3)/6);
almost(weighted[1].value,(20+30*2+40*3)/6);
almost(weighted[2].value,(30+40*2+50*3)/6);
const high=ma.calculate(candles,"SMA",3,"high");
almost(high[0].value,24);
const hl2=ma.calculate(candles,"SMA",3,"hl2");
almost(hl2[0].value,20);
const open=ma.calculate(candles,"SMA",3,"open");
almost(open[0].value,21);
const hlc3=ma.calculate(candles,"SMA",3,"hlc3");
almost(hlc3[0].value,20);
const ohlc4=ma.calculate(candles,"SMA",3,"ohlc4");
almost(ohlc4[0].value,20.25);
assert.equal(ma.calculate(candles,"EMA",6).length,0);
assert.equal(ma.calculate(candles,"BAD",3).length,0);
assert.equal(ma.calculate(candles,"EMA",NaN).length,0);
assert.equal(ma.calculate(candles,"EMA",3,"evil").length,0);
const cfg=(id="ma1")=>({id,type:"EMA",period:21,source:"close",color:"#68dfff",lineWidth:2,visible:true,label:""});
assert.equal(ma.normalizeList([cfg(),cfg()]),null);
assert.equal(ma.normalizeList(Array.from({length:17},(_,i)=>cfg("ma"+i))),null);
assert.equal(ma.normalize({...cfg(),period:0}),null);
assert.equal(ma.normalize({...cfg(),period:1001}),null);
assert.equal(ma.normalize({...cfg(),period:50.5}),null);
assert.equal(ma.normalize({...cfg(),color:"red"}),null);
assert.equal(ma.normalize({...cfg(),lineWidth:0}),null);
assert.equal(ma.normalize({...cfg(),visible:"true"}),null);
assert.equal(ma.normalize({...cfg(),label:"x".repeat(41)}),null);
assert.equal(ma.normalize({...cfg(),__protoNotAllowed:"hi"}),null);

const rma=ma.calculate(candles,"RMA",3);
almost(rma[0].value,20);almost(rma[1].value,80/3);almost(rma[2].value,310/9);
const smma=ma.calculate(candles,"SMMA",3);
almost(smma[0].value,20);almost(smma[1].value,80/3);almost(smma[2].value,310/9);
assert.deepEqual(Array.from(ma.calculate(candles,"RMA",1),x=>x.value),[10,20,30,40,50]);
assert.equal(ma.normalize({...cfg(),type:"RMA",period:1}).period,1);
assert.equal(ma.normalize({...cfg(),type:"SMMA",period:1000}).period,1000);
assert.equal(ma.normalize(cfg()).displayShift,0,"Legacy average configs default to no display shift");
assert.equal(ma.normalize({...cfg(),displayShift:-500}).displayShift,-500);
assert.equal(ma.normalize({...cfg(),displayShift:500}).displayShift,500);
assert.equal(ma.normalize({...cfg(),displayShift:501}),null);
assert.equal(ma.normalize({...cfg(),displayShift:-501}),null);
const shiftedRight=ma.shiftDisplay(candles,ma.calculate(candles,"SMA",3),1);
assert.deepEqual(Array.from(shiftedRight,x=>[x.time,x.value]),[[base+2700,20],[base+3600,30]]);
const shiftedLeft=ma.shiftDisplay(candles,ma.calculate(candles,"SMA",3),-1);
assert.deepEqual(Array.from(shiftedLeft,x=>[x.time,x.value]),[[base+900,20],[base+1800,30],[base+2700,40]]);
assert.equal(ma.normalize({...cfg(),period:0}),null);
assert.equal(ma.normalize({...cfg(),period:1001}),null);
assert.equal(ma.calculate(candles,"RMA",1001).length,0);
assert.equal(ma.normalize({...cfg(),source:"hlc3"}).source,"hlc3");
assert.equal(source.includes("order_send("),false);
assert.equal(source.includes("/api/modify_position"),false);
console.log("PASS configurable EMA/SMA/WMA/RMA/SMMA, 7 price sources, smoothing, warm-up, 1-1000 bounds and no trade writes");
