"use strict";
const assert=require("node:assert/strict");
global.window={};
require("../static/chart-studio-v5-overlay-feed.js");
const scope={account:"titan",symbol:"XAUUSD.p",timeframe:"M15"};
let current=[],clears=0,fetches=0;
global.fetch=()=>{fetches++;throw Error("network must not be used")};
const engine={setTransientOverlays(configs){current=configs.map(item=>({kind:item.kind,settings:{...item.settings}}));return {applied:true,count:current.length}},clearTransientOverlays(){current=[];clears++;return true}};
const feed=window.ChartStudioV5OverlayFeed.create(engine,scope);
const settings={supertrend:{enabled:true,period:10,multiplier:3},sar:{enabled:false,step:.02,maxStep:.2},donchian:{enabled:false,period:20},keltner:{enabled:false,period:20,atrPeriod:10,multiplier:2},atrBands:{enabled:false,period:20,atrPeriod:14,multiplier:2},linearRegression:{enabled:false,period:20,multiplier:2},ichimoku:{enabled:false,tenkanPeriod:9,kijunPeriod:26,senkouBPeriod:52,displacement:26},vwap:{enabled:false,timeZone:"UTC",sessionStart:"00:00"},pivots:{enabled:true},autoFib:{enabled:true},volume:{enabled:true}};
const first=feed.beginRead(),accepted=feed.update({scope,source:"CHART_STUDIO_LOCAL",canExecute:false,settings},first);
assert.deepEqual(accepted,{applied:true,count:1,kinds:["supertrend"]});
const currentSnapshot=JSON.stringify(current),stale=feed.beginRead();feed.beginRead();
assert.deepEqual(feed.update({scope,source:"CHART_STUDIO_LOCAL",canExecute:false,settings},stale),{applied:false,reason:"STALE_REQUEST"});
assert.equal(JSON.stringify(current),currentSnapshot,"stale requests leave newer overlays untouched");
settings.supertrend.enabled=false;
assert.equal(feed.update({scope,source:"CHART_STUDIO_LOCAL",canExecute:false,settings},feed.beginRead()).count,0,"disabled settings remove bridge-owned overlays");
settings.supertrend.enabled=true;
assert.equal(feed.update({scope:{...scope,account:"other"},source:"CHART_STUDIO_LOCAL",canExecute:false,settings},feed.beginRead()).reason,"SCOPE_MISMATCH");
assert.deepEqual(current,[],"scope mismatch clears prior managed state");
assert.equal(feed.update({scope,source:"SYNTHETIC",canExecute:false,settings},feed.beginRead()).reason,"UNVERIFIED_SOURCE");
settings.supertrend.period=0;
assert.equal(feed.update({scope,source:"CHART_STUDIO_LOCAL",canExecute:false,settings},feed.beginRead()).reason,"INVALID_SETTINGS");
assert.deepEqual(current,[],"invalid current settings fail closed");
settings.supertrend.period=10;feed.update({scope,source:"CHART_STUDIO_LOCAL",canExecute:false,settings},feed.beginRead());
assert.equal(feed.setScope({...scope,timeframe:"M5"}),true);assert.deepEqual(current,[],"explicit scope reset clears bridge state");
assert.equal(fetches,0);assert.ok(clears>=4);
console.log("PASS local v5 overlay feed scope, stale-token, disabled/invalid input and no-network contracts");
